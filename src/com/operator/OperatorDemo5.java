package com.operator;

public class OperatorDemo5 {
    public static void main(String[] args) {
        int a = 10;
        int b = 20;

        // a + b ----> a
        a += b;

        System.out.println(a);
        System.out.println(b);
    }
}
/*
 * 赋值运算符
 * = 直接赋值
 * += 加后赋值
 * -= 减后赋值
 * *= 乘后赋值
 * /= 除后赋值
 * %= 取余后赋值
 */