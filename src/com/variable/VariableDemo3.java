package com.variable;

public class VariableDemo3 {
    public static void main(String[] args) {
        int a, b, c, d;
        a = b = c = d = 1;

        System.out.println(a);
        System.out.println(b);
        System.out.println(c);
        System.out.println(d);
    }
}

