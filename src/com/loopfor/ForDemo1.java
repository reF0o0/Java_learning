package com.loopfor;

public class ForDemo1 {
    public static void main(String[] args) {
        for (int i = 1; i <= 5; i++) {
            System.out.println('跳');
        }
    }
}

/*
 * for（初始化语句；条件判断语句；条件控制语句）｛
 *     循环体语句
 * }
 * 初始化语句：循环的开始条件
 * 条件判断语句：循环的结束条件
 * 条件控制语句：控制变量如何变化
 * 循环体语句；要重复执行的代码
 */